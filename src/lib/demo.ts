export const DEMO_ANSWER = `**Суть:** линейная регрессия ищет прямую \`y = a·x + b\`, которая лучше всего (по методу наименьших квадратов) проходит через точки.

\`\`\`python
import numpy as np
from sklearn.linear_model import LinearRegression

# часы учёбы -> балл за тест
X = np.array([[1], [2], [3], [4], [5]])
y = np.array([52, 58, 65, 71, 78])

model = LinearRegression().fit(X, y)

print(model.coef_[0])      # a ≈ 6.5 — прирост балла за 1 час
print(model.intercept_)    # b ≈ 45.3 — балл при 0 часов
print(model.predict([[6]]))  # прогноз для 6 часов ≈ 84.3
\`\`\`

**Как объяснить студенту:**
1. Есть точки \`(x, y)\`, хотим прямую, которая "ближе всего" к ним.
2. "Ближе" значит минимум суммы квадратов ошибок \`Σ(yᵢ − (a·xᵢ + b))²\`.
3. \`fit\` находит \`a\` и \`b\`, \`predict\` считает \`y\` для нового \`x\`.

> Если спросят про качество: \`model.score(X, y)\` даёт R², чем ближе к 1, тем лучше прямая описывает данные.`;
